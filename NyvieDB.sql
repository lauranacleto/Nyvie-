
CREATE DATABASE NYVIEDB;
GO

USE NYVIEDB;
GO

CREATE TABLE Departamento (
 IdDepartamento UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
 Nome VARCHAR(150) NOT NULL,
);
GO

CREATE TABLE Cargo (
 IdCargo UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
 Nome VARCHAR(150) NOT NULL,
);
GO

CREATE TABLE StatusTicket (
 IdStatusTicket UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
 Nome VARCHAR(150) NOT NULL,
);
GO

CREATE TABLE Cliente (
 IdCliente UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
 Nome VARCHAR(150) NOT NULL,
 Telefone VARCHAR(20),
);
GO

CREATE TABLE Usuario (
    IdUsuario VARCHAR(40) PRIMARY KEY NOT NULL,
    Nome VARCHAR(150) NOT NULL,
    Imagem VARCHAR(255),
    Senha VARCHAR(255) NOT NULL,
    Telefone VARCHAR(20),
    Email VARCHAR(150) NOT NULL,
    IdDepartamento UNIQUEIDENTIFIER FOREIGN KEY REFERENCES Departamento(IdDepartamento),
    IdCargo UNIQUEIDENTIFIER FOREIGN KEY REFERENCES Cargo(IdCargo),
);
GO

CREATE TABLE Ticket (
    IdTicket UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
    Nome VARCHAR(150),
    Descricao VARCHAR(512) NOT NULL,
    Situacao VARCHAR(512) NOT NULL,
    DataHora DATETIME NOT NULL DEFAULT GETDATE(),
    Imagem VARCHAR(255),
    IdCliente UNIQUEIDENTIFIER FOREIGN KEY REFERENCES Cliente(IdCliente),
    IdUsuario VARCHAR(40) FOREIGN KEY REFERENCES Usuario(IdUsuario),
    IdStatusTicket UNIQUEIDENTIFIER FOREIGN KEY REFERENCES StatusTicket(IdStatusTicket),
    IdDepartamento UNIQUEIDENTIFIER FOREIGN KEY REFERENCES Departamento(IdDepartamento)
);
GO

CREATE TABLE TipoNotificacao (
    IdTipoNotificacao UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
    Nome VARCHAR(100) NOT NULL
);
GO

CREATE TABLE Notificacao (
    IdNotificacao UNIQUEIDENTIFIER PRIMARY KEY DEFAULT ((NEWID())),
    Descricao VARCHAR(500) NOT NULL,
    DataHora DATETIME NOT NULL DEFAULT GETDATE(),
    IdUsuario VARCHAR(40) FOREIGN KEY REFERENCES Usuario(IdUsuario),
    IdTicket UNIQUEIDENTIFIER  FOREIGN KEY REFERENCES Ticket(IdTicket),
    TipoNotificacaoID UNIQUEIDENTIFIER  FOREIGN KEY REFERENCES TipoNotificacao(IdTipoNotificacao),
);
GO